def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def latest_transcript(transcripts_dir: Path) -> Path:
    candidates = sorted(
        [
            path
            for path in transcripts_dir.glob("*.md")
            if path.is_file() and AGGREGATE_STEM not in path.stem
        ],
        key=lambda path: path.stat().st_mtime,
        reverse=True,
    )
    if not candidates:
        raise FileNotFoundError(f"No transcript .md files found in {transcripts_dir}")
    return candidates[0]


def resolve_transcript(value: str, deal_dir: Path) -> Path | None:
    lowered = value.lower()
    if lowered == "none":
        return None
    if lowered == "latest":
        return latest_transcript(deal_dir / "transcripts")
    if lowered == "all":
        deal_id = deal_dir.name.removeprefix("deal_")
        return build_all_deal_transcript_context(deal_dir, deal_id)

    path = Path(value)
    if not path.is_absolute():
        path = PROJECT_ROOT / path
    if not path.exists():
        raise FileNotFoundError(f"Transcript not found: {path}")
    return path


def transcript_text_for_prompt(transcript_path: Path | None, transcript_text: str) -> str:
    """Keep all-calls transcript text append-only so earlier calls remain cacheable."""
    if transcript_path is None or AGGREGATE_STEM not in transcript_path.stem:
        return transcript_text
    marker = "## Тексты звонков"
    marker_index = transcript_text.find(marker)
    return transcript_text[marker_index:] if marker_index >= 0 else transcript_text


def deal_prompt_cache_markers(transcript_text: str) -> list[str]:
    """Return up to three exact boundaries: global, prior calls, and all current calls."""
    markers = [DEAL_ID_SECTION_MARKER]
    call_markers = re.findall(r"^### Звонок[^\n]*", transcript_text, flags=re.MULTILINE)
    if call_markers:
        markers.append(call_markers[-1])
    markers.append(HISTORY_SECTION_MARKER)
    return markers


def resolve_history_path(deal_dir: Path, deal_id: str) -> Path:
    compact_path = deal_dir / "history" / f"deal_{deal_id}_llm_context.md"
    if compact_path.exists():
        return compact_path
    return deal_dir / "history" / f"deal_{deal_id}_customer_path.md"


def knowledge_files(knowledge_dir: Path) -> list[Path]:
    priority = [
        "index.md",
        "qualification.md",
        "technical_data.md",
        "risk_signals.md",
        "call_attempt_rules.md",
        "commercial_offer_followup.md",
        "manager_texts.md",
        "objections.md",
        "funnel.md",
    ]
    files = [knowledge_dir / name for name in priority if (knowledge_dir / name).exists()]
    excluded = {
        "attention_delta_core.md",
        "attention_delta_deal.md",
        "attention_delta_lead.md",
    }
    extra = sorted(
        path
        for path in knowledge_dir.glob("*.md")
        if path.name not in set(priority)
        and path.name.lower() != "readme.md"
        and path.name.lower() not in excluded
    )
    return files + extra


